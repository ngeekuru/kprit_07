package com.tnsif.java.intro;

public class loops {

	public static void main(String[] args) {
		for(int i=0;i<10;i++)
		{
			System.out.println(i);
		}
		
		int j =1;
		while(j<=10)
		{
			System.out.println("j values"+j);
			j++;	
		}
		
		//do while
		
		int k=1;
		do {
			System.out.println("k values"+k);
			k++;	
		}while(k>=10);
		
		
	}

}
